// build:web 后半段：把 web/index.html + web/dist/bundle.js 合成内联 HTML
// 字符串模块 web/dist/editor_html.ts，供 App.tsx 传给
// <WebView source={{ html: EDITOR_HTML, baseUrl: EDITOR_BASE_URL }}>。
// 为什么内联：NSH WebView 无 file:// / asset 文档协议（asset:/ 只给图片
// 字体），本任务不走 HTTP server —— html 字符串经 WebResourceRequested
// 拦截按 baseUrl 喂给 WebView2（见 task.md「web_view 接入方式」）。
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const distDir = path.join(here, 'dist');
const htmlPath = path.join(here, 'index.html');
const bundlePath = path.join(distDir, 'bundle.js');
const outPath = path.join(distDir, 'editor_html.ts');

const html = readFileSync(htmlPath, 'utf8');
const bundle = readFileSync(bundlePath, 'utf8');

if (bundle.length === 0) {
  console.error('[build-inline] web/dist/bundle.js 为空 —— esbuild 产物异常');
  process.exit(1);
}
if (/loro/i.test(bundle)) {
  console.error('[build-inline] web/dist/bundle.js 含 loro 引用 —— V9 定案禁止');
  process.exit(1);
}

// index.html 里的 <script src="./dist/bundle.js"></script> 换成内联 bundle。
const inlined = html.replace(
  /<script\s+src=["']\.\/dist\/bundle\.js["']\s*>\s*<\/script>/,
  () => `<script>\n${bundle}\n</script>`,
);
if (!inlined.includes(bundle)) {
  console.error('[build-inline] index.html 未找到 <script src="./dist/bundle.js"> 占位');
  process.exit(1);
}

mkdirSync(distDir, { recursive: true });
writeFileSync(
  outPath,
  '// GENERATED by web/build-inline.mjs — do not edit, do not commit.\n' +
    `export const EDITOR_HTML: string = ${JSON.stringify(inlined)};\n` +
    'export const EDITOR_BASE_URL: string = "https://cardmind.editor/";\n',
);
console.log(`[build-inline] ${outPath} (${inlined.length} bytes html)`);
